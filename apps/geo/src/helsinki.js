export function createHelsinki(camera, renderer, url = HELSINKI_URL) {
  const tiles = new TilesRenderer(url);
  tiles.errorTarget = 6;
  tiles.setCamera(camera);
  tiles.setResolutionFromRenderer(camera, renderer);
  tiles.group.matrixAutoUpdate = false;
  // The photos already hold the light of the day they were taken: draw them unlit.
  tiles.addEventListener('load-model', ({ scene }) => {
    scene.traverse((o) => {
      if (!o.isMesh) return;
      const old = o.material;
      // Marks its pixels in the stencil buffer: the terrain skips them (see main.js), so the
      // open terrain, lumpy this far north, never covers the real ground.
      o.material = new THREE.MeshBasicMaterial({
        map: old.map,
        stencilWrite: true,
        stencilRef: 1,
        stencilFunc: THREE.AlwaysStencilFunc,
        stencilZPass: THREE.ReplaceStencilOp,
      });
      o.renderOrder = -1;
      old.dispose();
    });
  });
  return {
    tiles,
    // Follow the main globe's frame (it moves when you recenter). No height offset needed:
    // measured over the bay, the mesh's water sits within a metre of the terrain's.
    update(globeGroup) {
      tiles.group.matrix.copy(globeGroup.matrixWorld);
      tiles.group.matrixWorldNeedsUpdate = true;
      tiles.group.updateMatrixWorld(true);
      tiles.update();
    },
  };
}
