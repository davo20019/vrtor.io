"""Copy the standalone building-3d-replicas skill into vrtor's .claude/skills/building-3d-replicas, adapted to vrtor.
  python3 scripts/3d/sync_skill.py [standalone repo, default ~/projects/building-3d-replicas]

The standalone repo is the source of truth for the process and the lessons: change them there, then run
this. vrtor differs only in where things live (scripts in scripts/3d/, each model in assets-src/<name>/ with
its own .venv), its worked examples, the headset test and Quest budgets (references/vrtor.md, written here).
Overwrites SKILL.md, references/ and assets/ in the vrtor skill; leaves OPEN-SOURCE.md alone.
"""
import re, shutil, sys
from pathlib import Path

SRC = Path(sys.argv[1] if len(sys.argv) > 1 else Path.home() / 'projects' / 'building-3d-replicas').expanduser()
DST = Path(__file__).resolve().parents[2] / '.claude' / 'skills' / 'building-3d-replicas'
if (SRC / 'skills' / 'building-3d-replicas' / 'SKILL.md').exists():   # the repo, not the skill folder
    SRC = SRC / 'skills' / 'building-3d-replicas'
if not (SRC / 'SKILL.md').exists():
    sys.exit(f'sync_skill: no SKILL.md in {SRC}')

def vrtor_paths(text):
    return text.replace('`scripts/', '`scripts/3d/').replace('(scripts/', '(scripts/3d/')

SETUP = """## Setup (vrtor)

`references/` and `assets/` are relative to this skill's directory; the scripts are in the repo's
`scripts/3d/`. Each model lives in `assets-src/<name>/` (`<model>` below) with its own environment:
`uv venv .venv && uv pip install --python .venv/bin/python build123d pillow numpy opencv-python-headless scipy`.
Run scripts as `<model>/.venv/bin/python scripts/3d/<name>.py`; each one's docstring documents its inputs.
Blender, Node and, for video, ffmpeg must be on PATH; run yt-dlp as `uvx yt-dlp@latest`.

Start a model from `assets/model-template/` or from the closest worked example (references/vrtor.md).

"""

skill = vrtor_paths((SRC / 'SKILL.md').read_text())
a, b = skill.index('## Setup'), skill.index('## Model folder')
skill = skill[:a] + SETUP + skill[b:]
skill = re.sub(r'9\. \*\*Test where it will be used\*\*.*?(?=\n## )',
               '9. **Headset test** at dev.vrtor.io, with the human: see [references/vrtor.md](references/vrtor.md); '
               'for WebXR details, [references/webxr.md](references/webxr.md).\n',
               skill, flags=re.S)
skill = skill.replace('- **Stop and ask after 5 review rounds without progress.**',
                      '- **Stop and ask after 5 review rounds without progress.**\n'
                      '- **vrtor:** frames, budgets, metal, the headset test and the worked examples are in '
                      '[references/vrtor.md](references/vrtor.md).')
skill = skill.replace('# Build an exact replica of a real object\n',
                      '# Build an exact replica of a real object\n\n'
                      '> vrtor\'s copy, generated by `scripts/3d/sync_skill.py` from the standalone skill '
                      '(github.com/davo20019/building-3d-replicas, locally ~/projects/building-3d-replicas). Change lessons there, then sync.\n')

for d in ('references', 'assets'):
    shutil.rmtree(DST / d, ignore_errors=True)
    shutil.copytree(SRC / d, DST / d)
for f in (DST / 'references').glob('*.md'):
    f.write_text(vrtor_paths(f.read_text()))
(DST / 'SKILL.md').write_text(skill)

(DST / 'references' / 'vrtor.md').write_text("""# vrtor specifics

## Worked examples

- `assets-src/altimeter/` (Alti-2 Galaxy altimeter): small, coloured, one front photo plus angled ones; the
  case is a smooth loft (spec.md, "Case shape"). Mounted on the left hand in /jump.
- `assets-src/cybertruck/` (Tesla Cybertruck): large, bare stainless steel, three photos fitted together,
  planar facets as half-spaces, wheels on steer and spin nodes, an interior audited against the published room
  dimensions (measure/cabin/audit.py). REPORT.md lists what went wrong and how it was fixed.
- The standalone repo's `examples/cowbell/` (CC0): five photos, graded against the museum's scan.
- `assets-src/heart/` (a normal adult heart, /hrt): no photos; the CT average of 19 adults as the shape, BodyParts3D
  carried onto it, valves, papillary muscles and chordae rebuilt to published sizes (refs/literature.md), and
  the beat as morph targets calibrated on chamber volumes (motion.py). The worked example for references/organic.md.

## Frame

Model in mm with the front facing +z and up +y; scale the root by 0.001 at export. Hand-held objects keep the
altimeter's convention (the GLB's front on +y, up on -z; vrtor's render_views.py defaults to it). Vehicles and
scenes are y-up in the GLB (front +z): convert the mesh data and node positions to Blender's frame on import
(`(x, -z, y)`), never rotate the root. Set `glbFrame` in `review.json` and write the frame in the `.json`.

## Headset test

Serve it at dev.vrtor.io (`node scripts/headset.js`, every subject, or `node scripts/headset.js <code>`) and
read `output/headset/<code>.log` while the human tests: fps, presses, errors. Start the page's log before
`createXr`, or the rig's own start wins and the page's state is never reported. Done means the human approved
it in the headset.

## Apps

- Metal: apps with a sky or reflection probe (`/jump`, `/spc`, `/taj`, `/mpc`, `/cyb`) can show real metal;
  elsewhere use metallic 0 with a clear coat, or add a probe like `/cyb`'s.
- `vite build --watch` ignores `public/`: after copying a new GLB into an app's `public/models/`, touch a
  source file so the watcher rebuilds, and check the served file's size.
- Budget for Quest: hand-held objects under 10k triangles, textures up to 1024 px, GLB under 500 KB;
  vehicles under 60k triangles, textures up to 2048 px, GLB under 3 MB, after build.sh.
""")
print('sync_skill: wrote', DST)
